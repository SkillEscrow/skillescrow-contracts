// Generates contracts/bounty_escrow/test-vectors/fee_vectors.txt.
//
// The expected values are computed here with plain BigInt arithmetic, independently of both the
// Rust contract (src/fees.rs) and the TypeScript helpers in skillescrow-app. Both of those are
// then checked against the same file. The file's SHA-256 is pinned in a test on each side, so
// the two copies cannot drift apart silently.
//
//   node scripts/gen-fee-vectors.mjs
//
// Line format (whitespace separated, '#' starts a comment):
//   <fn> <amount> <bps> <expected>
// where <fn> is fee, net or portion and <expected> is a decimal integer or "overflow".
import { writeFileSync } from 'node:fs';

const I128_MAX = (1n << 127n) - 1n;
const DENOM = 10_000n;

// fee(amount, bps) = floor(amount * bps / 10_000), "overflow" if amount * bps exceeds i128.
function fee(amount, bps) {
  const product = amount * bps;
  if (product > I128_MAX) return 'overflow';
  return (product / DENOM).toString();
}
function net(amount, bps) {
  const f = fee(amount, bps);
  return f === 'overflow' ? f : (amount - BigInt(f)).toString();
}

const UNIT = 10_000_000n;
const BIG = I128_MAX / DENOM;
const amounts = [
  0n, 1n, 2n, 9n, 10n, 11n, 19n, 99n, 100n, 101n, 9_999n, 10_000n, 10_001n,
  12_345_678n, 10_000_001n, UNIT, 100n * UNIT, 500n * UNIT,
  BIG - 1n, BIG, BIG + 1n, I128_MAX / 2n, I128_MAX,
];
const feeBps = [0n, 1n, 2n, 300n, 1000n, 10_000n];
const portionBps = [0n, 1n, 3_333n, 5_000n, 7_000n, 9_999n, 10_000n];

const lines = [
  '# Fee math test vectors. Generated by scripts/gen-fee-vectors.mjs: do not edit by hand.',
  '# Format: <fn> <amount> <bps> <expected>   (expected is an integer or "overflow")',
  '# Checked by src/fees.rs tests here and by packages/shared in skillescrow-app.',
];
for (const a of amounts) for (const b of feeBps) lines.push(`fee ${a} ${b} ${fee(a, b)}`);
for (const a of amounts) for (const b of feeBps) lines.push(`net ${a} ${b} ${net(a, b)}`);
for (const a of amounts) for (const b of portionBps) lines.push(`portion ${a} ${b} ${fee(a, b)}`);

const out = new URL('../contracts/bounty_escrow/test-vectors/fee_vectors.txt', import.meta.url);
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${lines.length - 3} vectors to contracts/bounty_escrow/test-vectors/fee_vectors.txt`);